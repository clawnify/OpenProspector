import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const source = readFileSync(new URL("../skills/linkedin-signals/SKILL.md", import.meta.url), "utf8");
const version = source.match(/^version: (\d+)$/m)?.[1];
if (!version) throw new Error("LinkedIn signal skill must declare an integer version");
const hash = createHash("sha256").update(source).digest("hex");
// Plain TS is bundled by both the local Worker and Clawnify's generated
// Wrangler configuration. No filesystem access or Markdown loader at runtime.
writeFileSync(new URL("../src/server/signal-skill.gen.ts", import.meta.url),
  `// Generated by scripts/build-signal-skill.mjs. Edit skills/linkedin-signals/SKILL.md.\n` +
  `export const signalSkill = ${JSON.stringify({ version, hash, content: source })} as const;\n`);
